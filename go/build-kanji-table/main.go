// build-kanji-table reads data/kanji.data and writes FastKanji.go, a sorted
// table of kanji keywords and code points, to stdout. It replaces
// scripts/build-kanji-ruby.rb, which wrote the Ruby file FastKanji.rb.
//
// Usage: go run ./build-kanji-table ../data/kanji.data > FastKanji.go
package main

import (
	"fmt"
	"os"
	"sort"
	"strings"
)

// kanji_keyword is the lowercase key under which a kanji can be found:
// its first English meaning, with spaces replaced by '*'.
func kanji_keyword(k *Kanji) string {
	return strings.ReplaceAll(strings.ToLower(k.english[0]), " ", "*")
}

type table_entry struct {
	key     string
	unicode int
}

func main() {
	kanji_data_file := "data/kanji.data" // The Ruby hard-codes this
	if len(os.Args) > 1 {
		kanji_data_file = os.Args[1]
	}

	kanji_by_keyword := map[string]*Kanji{} // keyword to kanji
	var kanji_with_unique_keyword []*Kanji
	duplicates_seen := 0

	// read and process the kanji datafile
	kanji_data, err := DataKanji_create_from_file(kanji_data_file)
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	for _, k := range kanji_data.kanji {
		for _, word := range k.english {
			idx := strings.ReplaceAll(strings.ToUpper(word), " ", "*")
			if kanji_by_keyword[idx] == nil {
				kanji_by_keyword[idx] = k
			}
		}
		// The first heisig keyword is used as a lowercase key
		kwd := kanji_keyword(k)
		if kanji_by_keyword[kwd] != nil {
			oh := kanji_by_keyword[kwd].heisig
			fmt.Fprintf(os.Stderr, "WARNING: seen [%s] again; ignoring this for [%d], already stored for [%d]\n", kwd, k.heisig, oh)
			duplicates_seen += 1
		} else {
			kanji_by_keyword[kwd] = k
			kanji_with_unique_keyword = append(kanji_with_unique_keyword, k)
		}
	}

	if duplicates_seen > 0 {
		fmt.Fprintf(os.Stderr, "WARNING: %d duplicates seen\n", duplicates_seen)
	}

	// Now output a suitable Go source file. The table is sorted so that
	// kanji_table_lookup can use a binary search.
	table := make([]table_entry, 0, len(kanji_with_unique_keyword))
	for _, k := range kanji_with_unique_keyword {
		table = append(table, table_entry{key: kanji_keyword(k), unicode: k.unicode})
	}
	sort.Slice(table, func(i, j int) bool { return table[i].key < table[j].key })

	fmt.Printf("// Code generated by build-kanji-table from %s; DO NOT EDIT.\n", kanji_data_file)
	fmt.Println()
	fmt.Println("package main")
	fmt.Println()
	fmt.Println("var kanji_table = []kanji_table_entry{")
	for _, e := range table {
		fmt.Printf("\t{%q, %d},\n", e.key, e.unicode)
	}
	fmt.Println("}")
}

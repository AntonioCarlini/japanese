// build-kanji-table reads data/kanji.data and writes FastKanji.go, a sorted
// table of kanji keywords and code points, to stdout. It replaces
// scripts/build-kanji-ruby.rb, which wrote the Ruby file FastKanji.rb.
//
// Usage: go run ./cmd/build-kanji-table ../data/kanji.data > FastKanji.go
package main

import (
	"bufio"
	"fmt"
	"io"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

// kanji_keyword is the lowercase key under which a kanji can be found:
// its first English meaning, with spaces replaced by '*'.
func kanji_keyword(k *Kanji) string {
	return strings.ReplaceAll(strings.ToLower(k.english[0]), " ", "*")
}

type table_entry struct {
	key     string
	unicode int
}

// build_table returns the table for the kanji in kanji_data, sorted by key so
// that kanji_table_lookup can use a binary search. Warnings about kanji that
// are left out are written to warnings.
//
// Every English meaning of a kanji is first registered in upper case (the
// first kanji to use it wins). Then the first meaning, in lower case, gives
// the key. If that key has been seen already, the kanji is left out, with a
// warning. This is how the Ruby does it, including one oddity: a first
// meaning without letters (such as "100") is the same in upper and lower case,
// so it collides with its own registration and the kanji is left out.
func build_table(kanji_data *DataKanji, warnings io.Writer) []table_entry {
	kanji_by_keyword := map[string]*Kanji{} // keyword to kanji
	var kanji_with_unique_keyword []*Kanji
	duplicates_seen := 0

	for _, k := range kanji_data.kanji {
		for _, word := range k.english {
			idx := strings.ReplaceAll(strings.ToUpper(word), " ", "*")
			if kanji_by_keyword[idx] == nil {
				kanji_by_keyword[idx] = k
			}
		}
		// The first heisig keyword is used as a lowercase key
		kwd := kanji_keyword(k)
		if kanji_by_keyword[kwd] != nil {
			oh := kanji_by_keyword[kwd].heisig
			fmt.Fprintf(warnings, "WARNING: seen [%s] again; ignoring this for [%d], already stored for [%d]\n", kwd, k.heisig, oh)
			duplicates_seen += 1
		} else {
			kanji_by_keyword[kwd] = k
			kanji_with_unique_keyword = append(kanji_with_unique_keyword, k)
		}
	}

	if duplicates_seen > 0 {
		fmt.Fprintf(warnings, "WARNING: %d duplicates seen\n", duplicates_seen)
	}

	table := make([]table_entry, 0, len(kanji_with_unique_keyword))
	for _, k := range kanji_with_unique_keyword {
		table = append(table, table_entry{key: kanji_keyword(k), unicode: k.unicode})
	}
	sort.Slice(table, func(i, j int) bool { return table[i].key < table[j].key })
	return table
}

// write_table writes the table as the Go source file FastKanji.go.
// data_file is only named in the header comment.
func write_table(w io.Writer, data_file string, table []table_entry) {
	fmt.Fprintf(w, "// Code generated by build-kanji-table from %s; DO NOT EDIT.\n", data_file)
	fmt.Fprintln(w)
	fmt.Fprintln(w, "package main")
	fmt.Fprintln(w)
	fmt.Fprintln(w, "var kanji_table = []kanji_table_entry{")
	for _, e := range table {
		fmt.Fprintf(w, "\t{%q, %d},\n", e.key, e.unicode)
	}
	fmt.Fprintln(w, "}")
}

func main() {
	kanji_data_file := "data/kanji.data" // The Ruby hard-codes this
	if len(os.Args) > 1 {
		kanji_data_file = os.Args[1]
	}

	// read and process the kanji datafile
	kanji_data, err := DataKanji_create_from_file(kanji_data_file)
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}

	table := build_table(kanji_data, os.Stderr)

	// Only the file name goes in the header, so that the output is the same
	// wherever the repository is checked out.
	out := bufio.NewWriter(os.Stdout)
	write_table(out, filepath.Base(kanji_data_file), table)
	if err := out.Flush(); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}
